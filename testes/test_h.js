(async()=>{try{
  await wait(900);
  const m=mesA, ant=mesAdd2(mesA,-1);
  const L=[];
  ['A','B','C','D','E','F','G','H','I'].forEach((c,i)=>L.push({valor:(10-i)*100,data:m+'-02',categoria:c,setor:'bebidas'}));
  L.push({valor:50,data:ant+'-10',categoria:'A',setor:'bebidas'});
  let ag=agregarGastos(L,'categoria',m,'dia');
  T('9 itens, todos especificados, sem Outros', ag.itens.length===9 && !ag.itens.some(x=>x.nome==='Outros'));
  T('menores aparecem um a um', ag.itens[7].nome==='H' && ag.itens[7].total===300 && ag.itens[8].nome==='I' && ag.itens[8].total===200);
  T('séries também uma a uma', ag.series.length===9);
  T('total = soma do mês', ag.total===5400);
  T('B sem mês anterior → deltaPct null', ag.itens.find(x=>x.nome==='B').deltaPct===null);
  T('A vs anterior: +1950%', Math.round(ag.itens.find(x=>x.nome==='A').deltaPct*100)===1900);
  const dias=new Date(+m.slice(0,4),+m.slice(5,7),0).getDate();
  T('eixo dia = dias do mês', ag.eixo.length===dias);
  T('série A dia 02 = 1000', ag.series.find(s=>s.nome==='A').pontos[1]===1000);
  const agm=agregarGastos(L,'categoria',m,'mes');
  T('eixo mês = 12 terminando no mês', agm.eixo.length===12 && agm.eixo[11]===m && agm.eixo[10]===ant);
  T('série A por mês: anterior 50', agm.series.find(s=>s.nome==='A').pontos[10]===50);
  const vazio=agregarGastos([],'categoria',m,'dia');
  T('vazio', vazio.itens.length===0 && vazio.total===0);
  const h=analiseHTML(vazio,{angulos:['categoria'],angulo:'categoria',modo:'dia',mes:m,acaoAngulo:'x',acaoModo:'y'});
  T('vazio mostra Nenhum gasto', h.includes('Nenhum gasto'));
  const hb=analiseHTML(ag,{angulos:['categoria'],angulo:'categoria',modo:'dia',mes:m,acaoAngulo:'x',acaoModo:'y'});
  T('tabela mostra novo', hb.includes('novo'));
  const F=[{valor:300,data:m+'-03',fornecedorNome:'Atacado Sul'},{valor:120,data:m+'-03'}];
  const af=agregarGastos(F,'fornecedor',m,'dia');
  T('fornecedor exclui sem fornecedor', af.total===300 && af.excluido===120);
  T('nota de excluídos', analiseHTML(af,{angulos:['fornecedor'],angulo:'fornecedor',modo:'dia',mes:m,acaoAngulo:'x',acaoModo:'y'}).includes('não entram nesta visão'));
  const sv=graficoPizza(ag.itens,ag.total);
  T('pizza svg sem NaN', sv.startsWith('<svg')&&!sv.includes('NaN'));
  const zl=graficoLinha(['01','02'],[{nome:'A',cor:'var(--s1)',pontos:[0,0]}]);
  T('linha zeros sem NaN', zl.startsWith('<svg')&&!zl.includes('NaN')&&!zl.includes('Infinity'));
  T('linha tem data-tip', graficoLinha(ag.eixo,ag.series).includes('data-tip='));
  fim();
}catch(e){out.push('ERR '+e.message+' '+(e.stack||'').split('\n')[1]);fim();}})();
