// Testes das regras do aviso dos Lembretes (funcoes/lembretes/lib.js). Uso: node testes/lembretes.test.mjs
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const L = require('../funcoes/lembretes/lib.js');
let ok = 0, ruim = 0;
const T = (n, c) => { if (c) ok++; else { ruim++; console.log('FAIL ' + n); } };
const ms = (d, h) => Date.parse(`${d}T${h}:00-03:00`);
const agora = ms('2026-11-15', '14:15');
const base = { titulo:'Reunião', quando:ms('2026-11-15', '14:30'), proxAviso:ms('2026-11-15', '14:15'), para:['u1'], concluido:false };
T('na hora do aviso manda', L.acao(base, agora) === 'mandar');
T('antes da hora não manda', L.acao(base, agora - 60000) === null);
T('sem aviso agendado não faz nada', L.acao({ ...base, proxAviso:null }, agora) === null);
T('concluído só limpa', L.acao({ ...base, concluido:true }, agora) === 'limpar');
T('atrasado até 2 h depois ainda manda', L.acao(base, ms('2026-11-15', '16:00')) === 'mandar');
T('mais de 2 h depois do compromisso só limpa', L.acao(base, ms('2026-11-15', '16:31')) === 'limpar');
T('texto: daqui a 15 min', L.quandoTxt(base.quando, agora) === 'Daqui a 15 min (14:30)');
T('texto: agora', L.quandoTxt(base.quando, base.quando) === 'Agora, 14:30');
T('texto: hoje com horas', L.quandoTxt(ms('2026-11-15', '16:45'), agora) === 'Hoje às 16:45 (daqui a 2 h 30 min)');
T('texto: amanhã', L.quandoTxt(ms('2026-11-16', '09:00'), agora) === 'Amanhã às 09:00');
T('texto: outro dia', L.quandoTxt(ms('2026-11-22', '08:00'), agora) === '22/11 às 08:00');
T('texto: virada do dia em Brasília (23:30 → amanhã 08:00)', L.quandoTxt(ms('2026-11-16', '08:00'), ms('2026-11-15', '23:30')) === 'Amanhã às 08:00');
const m = L.mensagem({ ...base, notas:'levar a lista', som:false, vibrar:true, fixo:true }, 'X1', agora);
T('mensagem tem título, quando e anotação', m.titulo === 'Reunião' && m.corpo === 'Daqui a 15 min (14:30) · levar a lista');
T('mensagem leva som, vibração e fixar como texto', m.som === '0' && m.vibrar === '1' && m.fixo === '1' && m.tag === 'lemb-X1' && m.url === './#/lembretes');
T('mensagem: tudo é texto', Object.values(m).every(v => typeof v === 'string'));
const aps = [{ uid:'u1', token:'a' }, { uid:'u1', token:'a' }, { uid:'u2', token:'b' }, { uid:'u3', token:'c' }, { uid:'u2' }];
T('manda só para quem foi escolhido, sem repetir', L.tokensPara(aps, ['u1', 'u2']).join() === 'a,b');
T('ninguém escolhido = ninguém recebe', L.tokensPara(aps, []).length === 0);
console.log(`lembretes: ${ok} ok` + (ruim ? `, ${ruim} falharam` : ''));
process.exit(ruim ? 1 : 0);
